"""
NGAFID-MC ingest and preprocessing.

The corpus is 5.4 GB of 1 Hz Parquet (Zenodo 6624956, CC-BY-4.0) and is not
bundled with this repository - the whole point of the adapter layer is that the
corpus is swappable. Point ``AEROTWIN_NGAFID_DIR`` at a directory of Parquet or
CSV flight files and this module reports on what it actually found: which
columns mapped, which are missing, how much of each channel is null.

Nothing here invents a column. If a channel is absent from the file it is
reported ABSENT, and the twin either derives it from physics (tagged
SIMULATED) or does without it.
"""

