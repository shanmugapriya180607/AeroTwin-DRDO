# --------------------------------------------------------------------------
# Cleaning
# --------------------------------------------------------------------------

def clean_value(key: str, value: float | None) -> float | None:
    """Range-gate a single sample. Out-of-range becomes None, never a guess."""
    if value is None:
        return None
    try:
        v = float(value)
    except (TypeError, ValueError):
        return None
    if math.isnan(v) or math.isinf(v):
        return None
    bounds = _RANGES.get(key)
    if bounds and not (bounds[0] <= v <= bounds[1]):
        return None
    return v


def interpolate_gaps(series: list, max_gap: int = 5) -> list:
    """Linear fill of short gaps only.

    A 1 Hz sensor dropping three samples is a dropout; filling it is reasonable.
    A sixty-second hole is a different flight condition and must stay a hole,
    otherwise the residual is computed against fabricated observations.
    """
    out = list(series)
    n = len(out)
    i = 0
    while i < n:
        if out[i] is not None:
            i += 1
            continue
        start = i
        while i < n and out[i] is None:
            i += 1
        end = i
        gap = end - start
        if gap > max_gap or start == 0 or end >= n:
            continue
        left, right = out[start - 1], out[end]
        if left is None or right is None:
            continue
        for j in range(start, end):
            u = (j - start + 1) / (gap + 1)
            out[j] = left + (right - left) * u
    return out


